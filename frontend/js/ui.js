export function escapeHtml(str) {
  if (!str) return '';
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}

// Toast notification system
let toastContainer = null;
export function showToast(message, type = 'info', duration = 3000) {
  if (!toastContainer) {
    toastContainer = document.createElement('div');
    toastContainer.className = 'toast-container';
    document.body.appendChild(toastContainer);
  }

  const toast = document.createElement('div');
  toast.className = `toast ${type}`;
  
  let iconHtml = '';
  if (type === 'success') {
    iconHtml = `<span style="color:var(--color-success);display:inline-flex;">${icons.check}</span>`;
  } else if (type === 'error') {
    iconHtml = `<span style="color:var(--color-danger);display:inline-flex;">${icons.close}</span>`;
  }

  toast.innerHTML = `
    <div class="toast-content">
      ${iconHtml}
      <span>${escapeHtml(message)}</span>
    </div>
    <button class="toast-close-btn" aria-label="Close notification">${icons.close}</button>
  `;

  const closeBtn = toast.querySelector('.toast-close-btn');
  closeBtn.addEventListener('click', () => {
    toast.classList.add('toast-exit');
    setTimeout(() => toast.remove(), 160);
  });

  toastContainer.appendChild(toast);

  setTimeout(() => {
    if (toast.parentElement) {
      toast.classList.add('toast-exit');
      setTimeout(() => toast.remove(), 160);
    }
  }, duration);
}

// Modal dialog helper
export function showConfirmModal({ title, body, confirmText = 'Confirm', danger = false, onConfirm }) {
  let backdrop = document.getElementById('confirm-modal-backdrop');
  if (!backdrop) {
    backdrop = document.createElement('div');
    backdrop.id = 'confirm-modal-backdrop';
    backdrop.className = 'modal-backdrop';
    document.body.appendChild(backdrop);
  }

  backdrop.innerHTML = `
    <div class="modal-dialog" role="dialog" aria-modal="true" aria-labelledby="modal-title">
      <div class="modal-header">
        <h3 id="modal-title" class="modal-title">${escapeHtml(title)}</h3>
        <button class="btn-icon modal-close-btn" aria-label="Close dialog">${icons.close}</button>
      </div>
      <div class="modal-body">${escapeHtml(body)}</div>
      <div class="modal-actions">
        <button class="btn btn-secondary modal-cancel-btn">Cancel</button>
        <button class="btn ${danger ? 'btn-danger' : 'btn-primary'} modal-confirm-btn">${escapeHtml(confirmText)}</button>
      </div>
    </div>
  `;

  requestAnimationFrame(() => {
    backdrop.classList.add('open');
  });

  const close = () => {
    backdrop.classList.remove('open');
  };

  backdrop.querySelector('.modal-close-btn').onclick = close;
  backdrop.querySelector('.modal-cancel-btn').onclick = close;
  backdrop.querySelector('.modal-confirm-btn').onclick = async () => {
    close();
    if (onConfirm) await onConfirm();
  };

  backdrop.onclick = (e) => {
    if (e.target === backdrop) close();
  };
}

export function formatTime(isoString) {
  if (!isoString) return '';
  const date = new Date(isoString);
  return date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
}

export function formatDateGroup(isoString) {
  if (!isoString) return 'Older';
  const date = new Date(isoString);
  const now = new Date();

  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const yesterday = new Date(today);
  yesterday.setDate(yesterday.getDate() - 1);
  const lastWeek = new Date(today);
  lastWeek.setDate(lastWeek.getDate() - 7);

  if (date >= today) return 'Today';
  if (date >= yesterday) return 'Yesterday';
  if (date >= lastWeek) return 'Previous 7 Days';
  return 'Older';
}
